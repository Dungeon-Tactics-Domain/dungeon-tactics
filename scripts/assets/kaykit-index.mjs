// Generates assets/kaykit/INDEX.md: each pack with number of models, files and size, and the name of each model per folder.
// node scripts/assets/kaykit-index.mjs  (run again whenever a pack is added, removed or changed)
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = 'assets/kaykit';
const isModel = (f) => /\.(gltf|glb)$/i.test(f);
// some KayKit packs name the glb "name.gltf.glb"; the model name is what comes before
const modelName = (f) => f.replace(/(\.gltf)?\.(gltf|glb)$/i, '');

function walk(dir, out = []) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

const mb = (b) => (b / 1048576).toLocaleString('en-US', { minimumFractionDigits: 1, maximumFractionDigits: 1 });
const packs = readdirSync(root, { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();
const rows = [];
const sections = [];
let totFiles = 0,
  totBytes = 0,
  totModels = 0;
for (const pack of packs) {
  const files = walk(path.join(root, pack));
  const bytes = files.reduce((s, f) => s + statSync(f).size, 0);
  const byDir = new Map();
  for (const f of files.filter((f) => isModel(f))) {
    const dir = path.relative(path.join(root, pack), path.dirname(f)).replaceAll('\\', '/');
    if (!byDir.has(dir)) byDir.set(dir, []);
    byDir.get(dir).push(modelName(path.basename(f)));
  }
  const models = [...byDir.values()].reduce((s, l) => s + l.length, 0);
  totFiles += files.length;
  totBytes += bytes;
  totModels += models;
  rows.push(`| [\`${pack}\`](#${pack}) | ${models} | ${files.length} | ${mb(bytes)} MB |`);
  sections.push(`## ${pack}\n`);
  for (const [dir, names] of [...byDir].sort())
    sections.push(`- \`${dir}/\` (${names.length}): ${names.sort().join(', ')}`);
  sections.push('');
}

writeFileSync(
  path.join(root, 'INDEX.md'),
  [
    '# KayKit model index',
    '',
    'Generated by `node scripts/assets/kaykit-index.mjs`; do not edit by hand. What each pack is, where it came from and how to use it: [README.md](README.md). Overview of all the game assets: [docs/ASSETS.md](../../docs/ASSETS.md).',
    '',
    '| Pack | Models | Files | Size |',
    '|---|---:|---:|---:|',
    ...rows,
    `| **Total** | **${totModels}** | **${totFiles}** | **${mb(totBytes)} MB** |`,
    '',
    ...sections,
  ].join('\n'),
);
console.log(`${packs.length} packs, ${totModels} models, ${totFiles} files, ${mb(totBytes)} MB`);
