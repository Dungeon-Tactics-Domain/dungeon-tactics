// Per-tile look of Beacon Hill (drawing only, the rules do not read it; Nov 12, proposal approved by Fernando): the enemy
// side (top-right corner, x - y >= 7) is in snow so you can read from afar which side each team starts on; the middle hill
// is rock, with a dark top; sand around the Beacon and gold under it; brick wall; 4 trees picked
// by position (fixed: the same map always draws the same).
function dressBeaconHill(grid: Grid, beacon: { x: number; y: number }): Grid {
  const tiles = grid.tiles.map((t, i) => {
    const x = i % grid.width,
      y = Math.floor(i / grid.width);
    const cold = x - y >= 7;
    const near = Math.abs(x - beacon.x) + Math.abs(y - beacon.y);
    const look =
      t.terrain === 'wall'
        ? 'brick'
        : t.terrain === 'forest'
          ? cold
            ? (x + y) % 2
              ? 'bare1'
              : 'bare2'
            : ['tree', 'tree2', 'tree3', 'tree4'][(x * 7 + y * 3) % 4]
          : near === 0
            ? 'gold'
            : near <= 2
              ? 'sand'
              : // since the Nov 13 relief the common ground sits at 2: rock only from 3, otherwise the heroes' side turned to stone
                cold
                ? t.h >= 3
                  ? 'snow_rock'
                  : 'snow'
                : t.h >= 4
                  ? 'summit'
                  : t.h >= 3
                    ? 'rock'
                    : 'grass';
    return { ...t, look };
  });
  return { ...grid, tiles };
}

// Ramps (Nov 13, Fernando's request: "more diagonal tiles… it's not Minecraft"): drawing only, the rules do not read `ramp`
// (the jump still follows the standing height). One letter per tile says where the ground rises (v > ^ <, FACING order) to the
// neighbor 1 level above; a dot is a flat tile. Hand-picked on the passages and slopes with a step of 1 (test in scenario-maps).
const RAMP_DIR: Record<string, number> = { v: 0, '>': 1, '^': 2, '<': 3 };
function withRamps(grid: Grid, overlay: string[]): Grid {
  const tiles = grid.tiles.map((t, i) => {
    const d = RAMP_DIR[overlay[Math.floor(i / grid.width)][i % grid.width]];
    return d === undefined ? t : { ...t, ramp: [d, 1] as [number, number] };
  });
  return { ...grid, tiles };
}

