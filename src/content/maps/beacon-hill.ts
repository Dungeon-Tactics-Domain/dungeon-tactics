// Per-tile look of Beacon Hill (drawing only, the rules do not read it; Nov 12, proposal approved by Fernando): the enemy
// side (top-right corner, x - y >= 7) is in snow so you can read from afar which side each team starts on; the middle hill
// is rock, with a dark top; sand around the Beacon and gold under it; brick wall; 4 trees picked
// by position (fixed: the same map always draws the same).
function dressBeaconHill(grid: Grid, beacon: { x: number; y: number }): Grid {
  const tiles = grid.tiles.map((t, i) => {
    const x = i % grid.width,
      y = Math.floor(i / grid.width);
    const cold = x - y >= 7;
    const near = Math.abs(x - beacon.x) + Math.abs(y - beacon.y);
    const look =
      t.terrain === 'wall'
        ? 'brick'
        : t.terrain === 'forest'
          ? cold
            ? (x + y) % 2
              ? 'bare1'
              : 'bare2'
            : ['tree', 'tree2', 'tree3', 'tree4'][(x * 7 + y * 3) % 4]
          : near === 0
            ? 'gold'
            : near <= 2
              ? 'sand'
              : // since the Nov 13 relief the common ground sits at 2: rock only from 3, otherwise the heroes' side turned to stone
                cold
                ? t.h >= 3
                  ? 'snow_rock'
                  : 'snow'
                : t.h >= 4
                  ? 'summit'
                  : t.h >= 3
                    ? 'rock'
                    : 'grass';
    return { ...t, look };
  });
  return { ...grid, tiles };
}

